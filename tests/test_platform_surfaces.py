"""The public bundle contains what the manifest says, and never the real site inputs.

The rule this file exists to hold: **`data/inputs/` is excluded by construction, not by
convention.** DEC-016 decided the real facility data stays private; a convention is something
a future change can breach without noticing, so it is a test.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
BUNDLE = REPO / "site/platform"
MANIFEST = BUNDLE / "surfaces.json"


@pytest.fixture(scope="module", autouse=True)
def _bundle_assembled():
    """Assemble the bundle if it is not already there.

    The copied surfaces (explorer, dashboard, contract, nfc) are GENERATED and therefore
    gitignored, so a clean checkout has the manifest but not the files it describes. Without
    this the tests pass locally - where a previous build left the copies behind - and fail on
    CI, which is exactly the shape of defect that had CI red for five commits earlier today.

    Building rather than skipping: a test that quietly skips on CI is a test that does not
    exist.
    """
    if not (BUNDLE / "explorer/index.html").is_file():
        result = subprocess.run(
            [sys.executable, str(REPO / "scripts/build_platform_surfaces.py")],
            cwd=REPO, capture_output=True, text=True)
        assert result.returncode == 0, result.stdout + result.stderr


@pytest.fixture(scope="module")
def surfaces() -> dict:
    return json.loads(MANIFEST.read_text())


def test_the_real_site_inputs_are_never_in_the_public_bundle():
    """DEC-016. The single most important assertion in this file."""
    forbidden_names = ["real_sites_v2.csv", "field_provenance_v1.csv",
                       "legacy_matlab_site_meta.csv", "matlab_scenarios.csv"]
    found = [str(p.relative_to(REPO)) for name in forbidden_names
             for p in BUNDLE.rglob(name)]
    assert found == [], f"real input data reached the public bundle: {found}"


def test_the_never_deploy_list_is_declared_and_honoured(surfaces):
    assert "data/inputs" in surfaces["never_deployed"]
    for banned in surfaces["never_deployed"]:
        leaked = [str(p.relative_to(REPO)) for p in BUNDLE.rglob("*")
                  if p.is_file() and banned.split("/")[-1] in p.parts]
        assert leaked == [], f"{banned} content appears in the bundle: {leaked[:3]}"


def test_the_deploy_note_states_the_exclusion(surfaces):
    note = surfaces["deploy_note"]
    assert "never copied" in note and "construction" in note
    assert "DEC-016" in note


def test_every_declared_surface_actually_exists(surfaces):
    """A manifest written by hand is a promise. This one is generated by looking, and this
    checks the looking was honest."""
    for s in surfaces["surfaces"]:
        if s.get("href") and not s["href"].startswith("http"):
            target = BUNDLE / s["href"]
            assert target.exists(), f"{s['id']} claims {s['href']}, which is not there"
        assert s["count"] > 0, f"{s['id']} claims zero items"


def test_tableau_links_use_the_share_form_not_the_page_form(surfaces):
    """The /views/ form is what embeds; /app/profile/ is the profile wrapper."""
    tableau = next(s for s in surfaces["surfaces"] if s["id"] == "tableau")
    for link in tableau["links"]:
        assert "/views/" in link["href"], f"{link['label']} uses the wrong URL form"
        assert "/app/profile/" not in link["href"]
        assert "viz_share_link" in link["href"]


def test_the_explorer_needs_no_cesium_token(surfaces):
    explorer = next(s for s in surfaces["surfaces"] if s["id"] == "explorer")
    assert "no Cesium account" in explorer["detail"] and "no token" in explorer["detail"]


def test_the_bundle_carries_no_credentials():
    r"""Reuses the repository's own secret scanner rather than defining "credential" twice.

    The first version of this test carried its own regex including a bare `\b\d{12}\b` for
    AWS account ids, and it fired on a 12-digit number inside minified third-party Cesium.
    Two definitions of what a credential looks like is one too many -- the weaker one
    eventually disagrees with the real gate, and you learn which by shipping.

    Vendored third-party code is excluded: it is not ours, it is not tracked, and we do not
    control its contents.
    """
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "_fcf_secret", REPO / "scripts/secret_scan.py")
    scanner = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(scanner)

    ours = [p for p in BUNDLE.rglob("*")
            if p.is_file()
            and p.suffix in {".js", ".json", ".html", ".css"}
            and "vendor" not in p.parts                 # third-party, not ours
            and p.stat().st_size < 4_000_000]
    assert ours, "found no bundle files to scan; the check would pass vacuously"

    problems = []
    for path in ours:
        for name, (pattern, label) in scanner.PATTERNS.items():
            for lineno, line in enumerate(path.read_text(errors="replace").splitlines(), 1):
                if pattern.search(line):
                    problems.append(f"{path.relative_to(REPO)}:{lineno}: {name} - {label}")
    assert problems == [], problems[:5]


def test_no_cesium_ion_token_is_present():
    """DEC-016: the offered token was declined. The explorer must work with none, and a token
    in a public bundle would be a credential in a shipped artifact."""
    import re
    token_like = re.compile(r"(?i)(ion\.defaultAccessToken\s*=\s*['\"][A-Za-z0-9._-]{20,}|"
                            r"Cesium\.Ion\.defaultAccessToken\s*=\s*['\"][A-Za-z0-9._-]{20,})")
    for path in BUNDLE.rglob("*.js"):
        if "vendor" in path.parts:
            continue
        hit = token_like.search(path.read_text(errors="replace"))
        assert not hit, f"{path.relative_to(REPO)} sets a Cesium ion token"


