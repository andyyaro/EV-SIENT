/* Interpret the generated field schema. Used by the entry forms AND by the parity test.
 *
 * There is exactly one copy of this logic and it is this file. The browser does not carry a
 * second, friendlier version of the model's refusals — that is the failure this whole design
 * exists to prevent, because a form that accepts what `observed.py` will later reject sends a
 * field worker away believing an observation was recorded when it was not.
 *
 * Every rule implemented here corresponds to a check in `observed.py`'s `__post_init__`.
 * Nothing here is stricter than the model, and nothing is looser.
 * `tests/test_field_schema_parity.py` runs the same candidate rows through this file and
 * through the Python and fails if a single verdict differs.
 *
 * Written as a plain script rather than an ES module so the page can load it with a bare
 * <script> tag exactly as it loads app.js, and so node can evaluate it with `vm` in the parity
 * test — the SAME bytes both times, which is the point.
 */
(function (root) {
  "use strict";

  /** Blank means "not provided". Matches pandas/_optional_float treating empty as None. */
  function isBlank(value) {
    return value === undefined || value === null || String(value).trim() === "";
  }

  /**
   * Parse a number the way the Python side does.
   * Returns {ok, value}. `ok:false` means "present but not a usable number", which is
   * different from absent — Python raises on `float("abc")` but treats blank as None.
   */
  function parseNumber(value) {
    if (isBlank(value)) return { ok: true, value: null };
    const n = Number(String(value).trim());
    if (!Number.isFinite(n)) return { ok: false, value: null };
    return { ok: true, value: n };
  }

  function fieldByName(form, name) {
    return form.fields.find((f) => f.name === name);
  }

  /**
   * Validate one row against one form.
   * Returns an array of {field, message}. Empty array means the model will accept it.
   */
  function validateRow(form, row) {
    const errors = [];
    const add = (field, message) => errors.push({ field, message });

    // -- presence and shape -------------------------------------------------------
    for (const field of form.fields) {
      const raw = row[field.name];
      if (field.required && isBlank(raw)) {
        add(field.name, `${field.label} is required.`);
        continue;
      }
      if (isBlank(raw)) continue;

      if (field.type === "number" || field.type === "integer") {
        const parsed = parseNumber(raw);
        if (!parsed.ok) {
          add(field.name, `${field.label} must be a number.`);
        } else if (field.type === "integer" && !Number.isInteger(parsed.value)) {
          add(field.name, `${field.label} must be a whole number.`);
        }
      }
      if (field.type === "date" && !/^\d{4}-\d{2}-\d{2}$/.test(String(raw).trim())) {
        add(field.name, `${field.label} must be a date (YYYY-MM-DD).`);
      }
    }

    // -- the model's own refusals -------------------------------------------------
    for (const rule of form.rules) {
      switch (rule.rule) {
        case "non_empty": {
          if (isBlank(row[rule.field])) add(rule.field, rule.message);
          break;
        }
        case "enum": {
          const value = row[rule.field];
          if (!isBlank(value) && !rule.values.includes(String(value).trim())) {
            add(rule.field, rule.message);
          }
          break;
        }
        case "at_least_one_of": {
          const anyPresent = rule.fields.some((name) => {
            const parsed = parseNumber(row[name]);
            return parsed.ok && parsed.value !== null;
          });
          if (!anyPresent) add(rule.fields[0], rule.message);
          break;
        }
        case "non_negative": {
          const parsed = parseNumber(row[rule.field]);
          if (!parsed.ok || (parsed.value !== null && parsed.value < 0)) {
            add(rule.field, rule.message);
          }
          break;
        }
        case "positive": {
          const parsed = parseNumber(row[rule.field]);
          if (!parsed.ok || parsed.value === null || !(parsed.value > 0)) {
            add(rule.field, rule.message);
          }
          break;
        }
        case "not_greater_than": {
          const left = parseNumber(row[rule.field]);
          const right = parseNumber(row[rule.than]);
          if (left.ok && right.ok && left.value !== null && right.value !== null
              && left.value > right.value + 1e-9) {
            add(rule.field, rule.message);
          }
          break;
        }
        default:
          // An unknown rule means the schema was generated by a newer builder than this
          // interpreter understands. Refuse rather than silently ignore it: a rule that
          // quietly does nothing is exactly how the form becomes more permissive than the
          // model.
          add(rule.field || "_schema",
              `This page cannot evaluate rule "${rule.rule}". Refusing rather than guessing.`);
      }
    }

    return errors;
  }

  /** Build the CSV text for a set of accepted rows, in the model's own column order. */
  function toCsv(form, rows) {
    const escape = (value) => {
      const text = value === undefined || value === null ? "" : String(value);
      return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
    };
    const lines = [form.csv_columns.join(",")];
    for (const row of rows) {
      lines.push(form.csv_columns.map((c) => escape(row[c])).join(","));
    }
    return lines.join("\n") + "\n";
  }

  root.FieldValidate = { validateRow, toCsv, isBlank, parseNumber, fieldByName };
})(typeof globalThis !== "undefined" ? globalThis : this);
