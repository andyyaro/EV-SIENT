"""Write www/data/stability.json from the engine's rank-stability reference output.

Usage: python3 site/redesign/tools/build_stability.py [--check] [REFERENCE_JSON] [OUT_JSON]

The source is reports/rank-stability/rank_stability_reference_12_sites.json, written by
scripts/build_rank_stability.py from src/fcf_m2/stability.py (method:
docs/methodology/rank_stability.md). Nothing here is computed afresh: the script only reshapes
the reference file for the public pages and refuses to write if it disagrees with the published
data (scores in sites.json, part points in scoring.json).

With --check it writes nothing and exits 1 if the file on disk differs from what it would write.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
WWW = os.path.join(REPO, 'site', 'redesign', 'www')

CHECK = '--check' in sys.argv
ARGS = [a for a in sys.argv[1:] if a != '--check']
REF = ARGS[0] if len(ARGS) > 0 else os.path.join(REPO, 'reports', 'rank-stability', 'rank_stability_reference_12_sites.json')
OUT = ARGS[1] if len(ARGS) > 1 else os.path.join(WWW, 'data', 'stability.json')


def pts(w):
    """A 0 to 1 weight as whole points out of 100."""
    return round(w * 100)


def main():
    ref = json.load(open(REF, encoding='utf-8'))
    if ref.get('schema') != 'evsient-rank-stability/1':
        raise SystemExit(f'{REF}: unexpected schema {ref.get("schema")!r}')
    published = {s['id']: s for s in json.load(open(os.path.join(WWW, 'data', 'sites.json'), encoding='utf-8'))['sites']}
    scoring = {s['id']: s for s in json.load(open(os.path.join(WWW, 'data', 'scoring.json'), encoding='utf-8'))['sites']}

    # The reference must describe the same sites, scores and part points the site already publishes.
    ref_ids = {s['siteId'] for s in ref['sites']}
    if ref_ids != set(published):
        raise SystemExit(f'reference sites {sorted(ref_ids)} differ from sites.json {sorted(published)}')
    for s in ref['sites']:
        sid = s['siteId']
        if abs(s['score'] - published[sid]['score']) > 1e-9 or s['rank'] != published[sid]['rank']:
            raise SystemExit(f'{sid}: reference rank/score {s["rank"]}/{s["score"]} differ from sites.json')
        for sub in s['subscores']:
            if abs(sub['shown'] - scoring[sid]['parts'][sub['key']]) > 1e-9:
                raise SystemExit(f'{sid} {sub["key"]}: reference points {sub["shown"]} differ from scoring.json')

    sens, rs, iu = ref['sensitivity'], ref['rankStability'], ref['inputUncertainty']
    spread = {w['key']: (round(w['low'] * 100), round(w['high'] * 100)) for w in rs['weightSpread']}
    names = {w['key']: w['label'] for w in rs['weightSpread']}
    spread_text = ', '.join(f'{names[k]} between about {lo} and {hi}' for k, (lo, hi) in spread.items())

    cases = []
    for c in sens['cases']:
        lead = c['leaders']
        cases.append({'part': c['subscore'], 'change': round(c['change']), 'first': lead[0]['siteId'], 'firstScore': lead[0]['score'],
                      'second': lead[1]['siteId'], 'secondScore': lead[1]['score'], 'topChanged': bool(c['topChanged'])})
    sf = sens.get('smallestFlip')
    smallest = {'part': sf['subscore'], 'from': round(sf['from'], 1), 'to': round(sf['to'], 1), 'newTop': sf['newTop']} if sf else None

    # Points the unconfirmed electrical capacity carries: the spare-capacity driver's full credit.
    cap_points = None
    for d in ref['sites'][0]['drivers']:
        if d['key'] == 'spare_capacity_kw_n':
            cap_points = round(d['max'], 2)
    scen = {s['key']: s for s in iu.get('scenarios', [])} if iu.get('done') else {}

    # Sites that share exactly the same feasibility subscore (the placeholder capacity at work).
    feas = {}
    for s in ref['sites']:
        v = next(x['value'] for x in s['subscores'] if x['key'] == 'feasibility')
        feas.setdefault(round(v, 2), []).append(s['siteId'])
    shared_value, shared_ids = max(feas.items(), key=lambda kv: len(kv[1]))

    sites = []
    for s in sorted(ref['sites'], key=lambda s: s['rank']):
        st, cap = s['stability'], s['inputRange'].get('capacity') if s.get('inputRange') else None
        row = {'id': s['siteId'], 'chanceFirst': round(st['pFirst'] * 100, 1), 'chanceTop3': round(st['pTop3'] * 100, 1),
               'rankLow': st['rankLow'], 'rankMedian': st['rankMedian'], 'rankHigh': st['rankHigh']}
        if cap:
            row['capacityRange'] = {'low': round(cap['low'], 1), 'high': round(cap['high'], 1), 'bestRank': cap['bestRank'], 'worstRank': cap['worstRank']}
        sites.append(row)

    doc = {
        'status': 'final',
        'source': 'Generated by site/redesign/tools/build_stability.py from reports/rank-stability/rank_stability_reference_12_sites.json '
                  '(src/fcf_m2/stability.py; method in docs/methodology/rank_stability.md). Do not edit by hand.',
        'asOf': ref.get('asOf'),
        'note': ref.get('note'),
        'method': {
            'step': round(sens['step']),
            'rescale': 'The other three weights are scaled in proportion, so the four still add up to 100.',
            'draws': rs['draws'],
            'spread': spread_text,
            'rangeNote': '5th to 95th percentile of the rank across the random weightings.',
        },
        'oneAtATime': cases,
        'smallestFlip': smallest,
        'inputs': {
            'capacityPoints': cap_points,
            'capacityCouldBeFirst': len(scen['capacity']['couldBeFirst']) if 'capacity' in scen else None,
            'unconfirmedCouldBeFirst': len(scen['unconfirmed']['couldBeFirst']) if 'unconfirmed' in scen else None,
            'sites': len(ref['sites']),
            'feasibilityShared': {'count': len(shared_ids), 'subscore': shared_value, 'ids': shared_ids},
        },
        'sites': sites,
    }
    text = json.dumps(doc, indent=1, ensure_ascii=False) + '\n'
    if '\u2014' in text:
        raise SystemExit('the reference text carries an em dash; the public site does not allow them')
    if CHECK:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != text:
            raise SystemExit(f'{OUT} is out of date: run build_stability.py to regenerate it')
        print(f'{OUT} is up to date')
        return
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {OUT}: {len(cases)} one-at-a-time cases, {len(sites)} sites')


if __name__ == '__main__':
    main()
