"""Generate the NFC tag payload table, QR fallbacks and the placement cards.

Everything here is derived from the contract. A tag pointing at a site id the contract does
not contain is a tag pointing at a 404 in a car park, so the site list is never typed by
hand.

Produces:
  docs/nfc/tag_payloads.csv        one row per tag: URL, byte count, exact NDEF hex
  docs/nfc/qr/<SITE_ID>.svg        the same URL as a QR code
  docs/nfc/PLACEMENT_CARDS.md      printable card per site, to sit beside each tag

The QR codes are not decoration. NFC is a convenience layer and must never be the only
door: a visitor with an older phone, a phone with NFC disabled, or no phone at all still
needs to reach the same page. Every card therefore carries the QR *and* the URL in text
large enough to type.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from fcf_m2 import nfc  # noqa: E402

OUT = REPO / "docs/nfc"
QR_DIR = OUT / "qr"


# --------------------------------------------------------------------------- QR encoding
# A minimal, dependency-free QR encoder would be a large amount of subtle code to get
# wrong. `segno` is a small, pure-Python, well-tested one. If it is unavailable the script
# still emits the payload table and the cards, and says plainly that the QR codes are
# missing rather than emitting a placeholder that looks like a QR code and is not.

def write_qr_codes(payloads) -> tuple[int, str | None]:
    try:
        import segno
    except ImportError:
        return 0, ("segno is not installed, so no QR codes were generated. "
                   "Install the [nfc] extra: pip install -e '.[nfc]'")
    QR_DIR.mkdir(parents=True, exist_ok=True)
    for payload in payloads:
        qr = segno.make(payload.url, error="h")   # high correction: these get scuffed
        qr.save(QR_DIR / f"{payload.site_id}.svg", scale=8, border=2, dark="#1B4332")
    return len(payloads), None


CARD = """
### {site_id} - {site_name}

<table>
<tr>
<td width="180"><img src="qr/{site_id}.svg" alt="QR code linking to the planning page for {site_id}" width="160"></td>
<td>

**What is being considered here**

This site is one of twelve being screened for possible public EV charging. Nothing has been
approved, funded, or scheduled.

**Tap the coin with your phone, or scan the code, or type:**

`{url}`

*Screening-class planning information. Not an approval, a permit, or a commitment.
Electrical capacity here is an unconfirmed placeholder.*

</td>
</tr>
</table>

---
"""


def main() -> int:
    payloads = nfc.payloads_from_contract(REPO / "data/contract/v1")
    OUT.mkdir(parents=True, exist_ok=True)

    table = nfc.summary_table(payloads)
    csv_path = OUT / "tag_payloads.csv"
    table.to_csv(csv_path, index=False, lineterminator="\n")

    count, warning = write_qr_codes(payloads)

    cards = [
        "# Printable placement cards\n",
        "*One card per site, to sit beside the tag. Generated by "
        "`scripts/build_nfc_tags.py` from the canonical contract - do not hand-edit.*\n",
        "\n> **Every destination is reachable without NFC.** Each card carries a QR code "
        "and the URL in plain text. NFC is a convenience layer, never the only door: a "
        "visitor with an older phone, with NFC switched off, or with no phone at all must "
        "still be able to reach the same page.\n",
        "\n> **Placement requires the facility manager's permission.** These cards do not "
        "grant it and must not be presented as though it has been given.\n",
    ]
    for payload in payloads:
        cards.append(CARD.format(site_id=payload.site_id, site_name=payload.site_name,
                                 url=payload.url))
    (OUT / "PLACEMENT_CARDS.md").write_text("\n".join(cards))

    print(f"wrote {csv_path.relative_to(REPO)} ({len(table)} tags)")
    print(f"wrote {(OUT / 'PLACEMENT_CARDS.md').relative_to(REPO)}")
    if warning:
        print(f"  ! {warning}")
    else:
        print(f"wrote {count} QR codes to {QR_DIR.relative_to(REPO)}/")
    print(f"largest payload: {max(p.byte_count for p in payloads)} bytes of "
          f"{nfc.NTAG215_USER_BYTES} available")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
